# BODMAS is an acronym for Brackets, Orders (i.e. powers and square roots, etc.), Division and Multiplication, Addition and Subtraction. It is a rule that defines the order of operations to evaluate a mathematical expression.

# B : Brackets
# O : Orders (i.e. powers and square roots, etc.)
# D : Division
# M : Multiplication
# A : Addition
# S : Subtraction